-- audit_logs is append-only evidence. It intentionally has no updated_at, updated_by or
-- is_deleted columns: rows are never edited or soft-deleted. The triggers below reject
-- UPDATE, DELETE and TRUNCATE. A table owner can still disable triggers, so the application
-- must connect with a role that does not own the table and has only INSERT and SELECT.
-- Neon roles are managed in the Neon console; the DBA runs, for the app role:
--   REVOKE UPDATE, DELETE, TRUNCATE ON audit_logs FROM <app_role>;
--   GRANT INSERT, SELECT ON audit_logs TO <app_role>;
--   GRANT USAGE ON SEQUENCE audit_logs_id_seq TO <app_role>;
-- No foreign keys: audit rows must survive the rows they describe.
CREATE TABLE audit_logs (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type   varchar(100) NOT NULL,
  entity_type  varchar(100) NOT NULL,
  entity_id    varchar(100) NULL,
  company_id   integer      NULL,
  performed_by integer      NULL,
  performed_at timestamptz  NOT NULL DEFAULT now(),
  old_value    jsonb        NULL,
  new_value    jsonb        NULL,
  ip_address   varchar(45)  NULL,
  user_agent   varchar(500) NULL,
  created_at   timestamptz  NOT NULL DEFAULT now(),
  created_by   integer      NULL
);
CREATE INDEX ix_audit_logs_entity ON audit_logs (entity_type, entity_id, performed_at);
CREATE INDEX ix_audit_logs_company_performed_at ON audit_logs (company_id, performed_at);

CREATE TRIGGER trg_audit_logs_reject_change
  BEFORE UPDATE OR DELETE ON audit_logs
  FOR EACH ROW EXECUTE FUNCTION reject_audit_log_change();
CREATE TRIGGER trg_audit_logs_reject_truncate
  BEFORE TRUNCATE ON audit_logs
  FOR EACH STATEMENT EXECUTE FUNCTION reject_audit_log_change();

